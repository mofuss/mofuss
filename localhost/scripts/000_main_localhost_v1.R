# Date: Apr 2026
# Execution: Source from RStudio; Dinamica EGO does not invoke this script directly.
#
# Purpose: Orchestrate the local MoFuSS preprocessing workflow, selecting and
# sourcing the required numbered scripts for the configured demand scenario.
# Inputs: RStudio script location, .env/process credentials and parameters.csv.
# Outputs: All products generated by the sourced preprocessing scripts.
# Side effects: Sources multiple scripts, copies demand inputs and may send
